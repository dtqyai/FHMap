"""Build viewport-loadable WebP pyramids from the preserved source PNGs."""
from pathlib import Path
from concurrent.futures import ThreadPoolExecutor
from PIL import Image
import hashlib,json,math

ROOT=Path(__file__).resolve().parents[1]
CAL=json.loads((ROOT/'source/map-calibration.json').read_text())
CROPS={'main':[1415,846,6100,6363],'hotwheels':[900,1200,4400,3900]}
NAMES={'main':'澳洲大陆','blizzard':'暴风雪山','hotwheels':'风火轮'}
# Blizzard uses the reference map axes; the source PNG has a different orientation.
REFERENCE_CROPS={'blizzard':[0,1228,538,629]}
SIZE=512
QUALITY=85
units={k:1/math.sqrt(v['oldToImage'][0][0]*v['oldToImage'][1][1]-v['oldToImage'][0][1]*v['oldToImage'][1][0]) for k,v in CAL.items()}
positions={key:[0,0] for key in CAL}
configs={}
report={}
for key,item in CAL.items():
    source=ROOT/'source/originals'/item['image'];crop=CROPS.get(key)
    reference_crop=REFERENCE_CROPS.get(key)
    if reference_crop:
        rx,ry,rw,rh=reference_crop;s=1/units[key]
        crop=[0,0,math.ceil(rw*s),math.ceil(rh*s)]
        old_to_map=[[s,0,-rx*s],[0,s,-ry*s]]
    cx,cy,cw,ch=crop
    if not source.is_file():
        raise SystemExit(f'Missing source image: {source}. See README.md for local source image setup.')
    digest=hashlib.sha256()
    with source.open('rb') as stream:
        for chunk in iter(lambda:stream.read(1024*1024),b''):digest.update(chunk)
    digest.update(json.dumps([crop,SIZE,QUALITY,'webp-method4-v1']).encode())
    if reference_crop:digest.update(json.dumps([reference_crop,item['oldToImage'],'reference-aligned-v1']).encode())
    base=Path('assets/maps')/key/digest.hexdigest()[:12]
    max_level=math.ceil(math.log2(max(cw,ch)/SIZE))
    levels=[];tile_bytes=[]
    print('Building',item['image'],flush=True)
    with Image.open(source) as original:
        if reference_crop:
            a,b=item['oldToImage']
            # Pillow samples the source PNG using reference-aligned output pixels.
            output_to_source=(a[0]/s,a[1]/s,a[0]*rx+a[1]*ry+a[2],b[0]/s,b[1]/s,b[0]*rx+b[1]*ry+b[2])
            cropped=original.transform((cw,ch),Image.Transform.AFFINE,output_to_source,Image.Resampling.BICUBIC).convert('RGB')
        else:
            cropped=original.crop((cx,cy,cx+cw,cy+ch)).convert('RGB')
    for z in range(max_level+1):
        divisor=2**(max_level-z)
        w,h=math.ceil(cw/divisor),math.ceil(ch/divisor)
        level=cropped if divisor==1 else cropped.resize((w,h),Image.Resampling.LANCZOS)
        cols,rows=math.ceil(w/SIZE),math.ceil(h/SIZE)
        folder=ROOT/base/str(z);folder.mkdir(parents=True,exist_ok=True)
        def save_tile(position):
            x,y=position;path=folder/f'{x}-{y}.webp'
            level.crop((x*SIZE,y*SIZE,min((x+1)*SIZE,w),min((y+1)*SIZE,h))).save(path,'WEBP',quality=QUALITY,method=4)
            return path.stat().st_size
        with ThreadPoolExecutor(max_workers=4) as pool:
            tile_bytes.extend(pool.map(save_tile,((x,y) for y in range(rows) for x in range(cols))))
        levels.append({'z':z,'width':w,'height':h,'cols':cols,'rows':rows})
        print(key,'level',z,cols*rows,'tiles',flush=True)
        if divisor!=1:level.close()
    cropped.close()
    configs[key]={'name':NAMES[key],'sourceImage':item['image'],'width':item['width'],'height':item['height'],'crop':crop,'unit':units[key],'position':positions[key],'oldToImage':item['oldToImage'],'tiles':{'size':SIZE,'base':base.as_posix(),'levels':levels}}
    if reference_crop:configs[key].update(referenceCrop=reference_crop,oldToMap=old_to_map)
    report[key]={'sourceBytes':source.stat().st_size,'tileCount':len(tile_bytes),'tileBytes':sum(tile_bytes),'largestTileBytes':max(tile_bytes),'previewBytes':(ROOT/base/'0/0-0.webp').stat().st_size}
(ROOT/'maps.js').write_text('/* Generated by scripts/build-tiles.py. Source PNGs are never requested by the viewer. */\nwindow.FH3_MAPS = '+json.dumps(configs,ensure_ascii=False,indent=2)+';\n')
(ROOT/'source/tile-build.json').write_text(json.dumps(report,indent=2)+'\n')
print(json.dumps(report,indent=2),flush=True)
