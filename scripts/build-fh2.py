"""Build FH2 data and viewport tiles from the recorded points and preserved PNGs."""
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path
import hashlib
import json
import math
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
CAL = json.loads((ROOT / 'source/fh2-map-calibration.json').read_text())
MAIN = json.loads((ROOT / 'source/fh2-extracted-points.json').read_text())
STORM = json.loads((ROOT / 'source/fh2-storm-points.json').read_text())
SIZE, QUALITY = 512, 85
REGIONS = {
    'fh2-main': ('法国与意大利', [500, 350, 6200, 3300], '本体',
                 {'name': 'KudosPrime', 'url': MAIN['url']}),
    'fh2-storm': ('风暴岛', [900, 500, 5000, 2900], 'DLC',
                  {'name': 'Maka91', 'url': STORM['url']}),
}
TYPES = {
    1: ('快速移动广告牌', '快速移动', '#f34599', 'travel', 50),
    2: ('XP 广告牌', 'XP 广告牌', '#f7c85b', 'XP', 100),
    3: ('车房宝物', '车房宝物', '#a998f7', 'barn', 10),
    4: ('测速照相', '测速照相', '#69d9c6', 'camera', 30),
    5: ('测速区间', '测速区间', '#ff9554', 'camera', 15),
    12: ('速度与激情 · 奖励广告牌', '速度与激情 · 广告牌', '#84d0f9', '奖', 20),
    14: ('速度与激情 · 测速照相', '速度与激情 · 测速照相', '#84d0f9', 'camera', 10),
    15: ('速度与激情 · 测速区间', '速度与激情 · 测速区间', '#f7c85b', 'camera', 5),
    20: ('风暴岛 · 奖励广告牌', '奖励广告牌', '#84d0f9', '奖', 25),
}
TYPES[21] = ('风暴岛 · 车房宝物', '车房宝物', '#a998f7', 'barn', 1)
types = {}
for key, (name, short, color, icon, total) in TYPES.items():
    item = dict(name=name, short=short, color=color, icon=icon, total=total,
                region='fh2-storm' if key >= 20 else 'fh2-main')
    types[key] = item
points = [[p['id'], p['type'], p['left'] + p['width'] / 2,
           p['top'] + p['height'] / 2, ''] for p in MAIN['markers']]
points.extend([p['id'], 20, p['x'], p['y'], ''] for p in STORM['boards'])
p = STORM['barn']
points.append([p['id'], 21, p['x'], p['y'], '车房宝物 · MG Metro 6R4'])
(ROOT / 'data-fh2.js').write_text(
    '/* Generated by scripts/build-fh2.py. Source records are in source/fh2-*.json. */\n'
    + 'window.FH2_DATA = ' + json.dumps(dict(source=MAIN['url'], types=types, points=points),
                                        ensure_ascii=False, indent=2) + ';\n')
configs, report = {}, {}
for key, (name, crop, tag, point_source) in REGIONS.items():
    item = CAL[key]
    source = ROOT / 'source/originals' / item['image']
    if not source.is_file():
        raise SystemExit(f'Missing source image: {source}')
    source_hash = hashlib.sha256(source.read_bytes()).hexdigest()
    digest = hashlib.sha256((source_hash + json.dumps([crop, SIZE, QUALITY, 'webp-method4-v1'])).encode())
    base = Path('assets/maps') / key / digest.hexdigest()[:12]
    cx, cy, cw, ch = crop
    max_level = math.ceil(math.log2(max(cw, ch) / SIZE))
    levels, tile_bytes = [], []
    with Image.open(source) as original:
        cropped = original.crop((cx, cy, cx + cw, cy + ch)).convert('RGB')
    for z in range(max_level + 1):
        divisor = 2 ** (max_level - z)
        w, h = math.ceil(cw / divisor), math.ceil(ch / divisor)
        level = cropped if divisor == 1 else cropped.resize((w, h), Image.Resampling.LANCZOS)
        cols, rows = math.ceil(w / SIZE), math.ceil(h / SIZE)
        folder = ROOT / base / str(z)
        folder.mkdir(parents=True, exist_ok=True)
        def save_tile(position):
            x, y = position
            path = folder / f'{x}-{y}.webp'
            level.crop((x * SIZE, y * SIZE, min((x + 1) * SIZE, w),
                        min((y + 1) * SIZE, h))).save(path, 'WEBP', quality=QUALITY, method=4)
            return path.stat().st_size
        with ThreadPoolExecutor(max_workers=4) as pool:
            tile_bytes.extend(pool.map(save_tile, ((x, y) for y in range(rows) for x in range(cols))))
        levels.append(dict(z=z, width=w, height=h, cols=cols, rows=rows))
        print(key, 'level', z, cols * rows, 'tiles', flush=True)
        if divisor != 1:
            level.close()
    cropped.close()
    a, b = item['oldToImage']
    unit = 1 / math.sqrt(a[0] * b[1] - a[1] * b[0])
    configs[key] = dict(name=name, tag=tag, sourceImage=item['image'],
                        width=item['width'], height=item['height'], crop=crop, unit=unit,
                        position=[0, 0], oldToImage=item['oldToImage'], pointSource=point_source,
                        tiles=dict(size=SIZE, base=base.as_posix(), levels=levels))
    if key == 'fh2-storm':
        configs[key]['additionalPointSource'] = dict(name='Classy Tech Calibrations', url=STORM['barn']['url'])
    report[key] = dict(sourceSHA256=source_hash, sourceBytes=source.stat().st_size,
                       tileCount=len(tile_bytes), tileBytes=sum(tile_bytes),
                       largestTileBytes=max(tile_bytes),
                       previewBytes=(ROOT / base / '0/0-0.webp').stat().st_size)
(ROOT / 'maps-fh2.js').write_text('/* Generated by scripts/build-fh2.py. */\nwindow.FH2_MAPS = '
                                + json.dumps(configs, ensure_ascii=False, indent=2) + ';\n')
(ROOT / 'source/fh2-tile-build.json').write_text(json.dumps(report, indent=2) + '\n')
print(json.dumps(report, indent=2), flush=True)
